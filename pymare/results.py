def _expand_unit_order(order, group_codes, n_obs):
    """Turn a permutation of exchangeable units into a row index array.

    Parameters
    ----------
    order : :obj:`numpy.ndarray` of shape (m,)
        A permutation of the exchangeable units. ``order[k]`` is the unit whose
        estimates are moved onto unit ``k``'s rows.
    group_codes : None or :obj:`numpy.ndarray` of shape (K,)
        Consecutive group codes, one per row, or None when rows are the units.
    n_obs : :obj:`int`
        Number of rows.

    Returns
    -------
    :obj:`numpy.ndarray` of shape (K,)
        Row indices realising ``order`` while leaving the group layout alone.

    Notes
    -----
    Dependent rows are exchangeable only as complete groups, so a shuffle has to
    move whole groups rather than individual rows. Shuffling rows independently
    generates datasets that could not have arisen under the null and builds a
    reference distribution that is far too narrow.

    The refit is vectorized over permutations and therefore sees one design and
    one set of group labels for every column, so a permutation may only move a
    group's estimates onto rows that carry the same label as each other. Writing
    each source group into the *positions* of the group it replaces preserves
    that, whereas concatenating groups in the permuted order does not: it assumes
    the labels are contiguous and equally sized, and silently splits a group
    across two labels otherwise -- for interleaved labels even under the identity
    permutation. :func:`_exchangeable_unit_classes` supplies the permutations for
    which the sizes line up.
    """
    if group_codes is None:
        return order
    members = [np.flatnonzero(group_codes == unit) for unit in range(order.size)]
    rows = np.empty(n_obs, dtype=np.intp)
    for unit, source in enumerate(order):
        rows[members[unit]] = members[source]
    return rows


def _exchangeable_unit_classes(group_codes, n_units):
    """Split the exchangeable units into sets that may be permuted with each other.

    Parameters
    ----------
    group_codes : None or :obj:`numpy.ndarray` of shape (K,)
        Consecutive group codes, one per row, or None when rows are the units.
    n_units : :obj:`int`
        Number of exchangeable units.

    Returns
    -------
    :obj:`list` of :obj:`numpy.ndarray`
        Unit indices, partitioned by the number of rows each unit contributes.

    Notes
    -----
    A permuted dataset is refit against the original group labels, so a group of
    three rows can only take the place of another group of three rows. Groups of
    equal size -- the usual case, and the only one the enumeration used to
    consider -- form a single class and give the full ``m!`` permutations back.
    """
    if group_codes is None:
        return [np.arange(n_units)]
    sizes = np.bincount(group_codes, minlength=n_units)
    return [np.flatnonzero(sizes == size) for size in np.unique(sizes)]


def _iter_unit_orders(classes, n_units):
    """Enumerate every permutation that keeps each unit within its size class."""
    for assignment in itertools.product(*(itertools.permutations(c.tolist()) for c in classes)):
        order = np.empty(n_units, dtype=np.intp)
        for positions, sources in zip(classes, assignment):
            order[positions] = sources
        yield order


def _random_unit_order(classes, n_units):
    """Draw one permutation that keeps each unit within its size class."""
    order = np.empty(n_units, dtype=np.intp)
    for positions in classes:
        order[positions] = np.random.permutation(positions)
    return order


class MetaRegressionResults:
    """Container for results generated by PyMARE meta-regression estimators.

    Parameters
    ----------
    estimator : :obj:`~pymare.estimators.BaseEstimator`)
        The estimator used to produce the results.
    dataset : :obj:`~pymare.core.Dataset`)
        A Dataset instance containing the inputs to the estimator.
    fe_params : :obj:`numpy.ndarray` of shape (p, d)
        Fixed-effect coefficients. Must be a 2-d numpy array with shape p x d,
        where p is the number of predictors, and d is the number of parallel datasets
        (typically 1).
    fe_cov : :obj:`numpy.ndarray` of shape (p, p)
        The p x p *covariance* matrix of the fixed effects, ``(X'WX)^-1`` (or its
        cluster-robust replacement). Despite the ``"inv_cov"`` key it arrives
        under, this is a covariance, not an inverse covariance or a precision
        matrix -- :attr:`fe_se` takes ``sqrt(diagonal(...))`` of it, which is
        only meaningful for a covariance.
    tau2 : None or :obj:`numpy.ndarray` of shape (d,) or :obj:`float`, optional
        A 1-d array containing the estimated tau^2 value for each parallel dataset
        (or a float, for a single dataset). May be omitted by fixed-effects estimators.

    Warning
    -------
    When an Estimator is fitted to arrays directly using the ``fit`` method, the Results object's
    utility is limited.
    Many methods will not work.
    """

    def __init__(self, estimator, dataset, fe_params, fe_cov, tau2=None):
        self.estimator = estimator
        self.dataset = dataset
        self.fe_params = fe_params
        self.fe_cov = fe_cov
        self.tau2 = tau2

    def _tau2_model(self):
        """Return the working model the estimator recorded for tau^2.

        Returns
        -------
        :obj:`str`
            One of ``TAU2_INDEPENDENT``, ``TAU2_CORRELATED`` or
            ``TAU2_AGGREGATE``; see :data:`pymare.stats.TAU2_INDEPENDENT`.

        Notes
        -----
        Read from the fitted estimator rather than re-derived from
        ``weight_scheme`` here. The two used to be worked out independently, and
        the interval, Q and the permutation null could each describe a different
        set of units from the tau^2 they accompanied. Estimators that predate the
        attribute, or that were fitted to arrays alone, report independence.
        """
        return getattr(self.estimator, "tau2_model_", TAU2_INDEPENDENT)

    def _analysis_arrays(self):
        """Return the units and weighting that result statistics must describe.

        Returns
        -------
        :obj:`tuple`
            ``(y, v, X, groups)``. ``groups`` is None unless the statistics have
            to be computed under the correlated-effects working model, in which
            case every row is kept and :func:`~pymare.stats.q_gen` reweights them
            rather than aggregating.
        """
        y = self.dataset.y
        v = broadcast_columns(self.estimator.get_v(self.dataset), y.shape[1])
        X = self.dataset.X
        groups = getattr(self.dataset, "g", None)
        model = self._tau2_model()

        if model == TAU2_CORRELATED:
            # tau^2 came from the observation-level correlated-effects model, so
            # Q and the interval have to as well; q_gen applies the same weights.
            return y, v, X, np.asarray(groups).ravel()
        if model != TAU2_AGGREGATE:
            return y, v, X, None

        # Collapse the same way the estimator did. Sample-size-based
        # estimators aggregate on n, so reduce n and derive v from it rather
        # than collapsing a v the estimator never used; otherwise these
        # statistics describe a different aggregation from the one that
        # produced tau^2.
        rho = getattr(self.estimator, "rho", DEFAULT_RHO)
        if "v" in getfullargspec(self.estimator.fit).args[1:]:
            y, v, X = collapse_groups(y, v, X, groups, rho=rho)
        else:
            sigma2 = np.asarray(self.estimator.params_["sigma2"], dtype=float)
            y, n, X = collapse_groups_by_n(y, self.dataset.n, X, groups, rho=rho)
            v = sigma2 / n
        return y, v, X, None

    def _permutation_arrays(self):
        """Return the estimator inputs the permutation refit must reproduce.

        Notes
        -----
        This is a narrower condition than :meth:`_tau2_model`, which also has a
        reduction to report for ``"rescale"``. A permutation test compares the
        observed statistic against the same statistic recomputed on permuted
        data, so the arrays here have to be the ones the estimator actually
        fitted. Only ``"collapse"`` fits one row per group; ``"rescale"`` keeps
        every row and only reweights it. Collapsing for ``"rescale"`` built the
        null from a different model than the observed coefficient, so the two
        disagreed whenever predictors or variances varied within a group.
        """
        y = self.dataset.y
        X = self.dataset.X
        groups = getattr(self.dataset, "g", None)
        has_v = "v" in getfullargspec(self.estimator.fit).args[1:]
        second = self.dataset.v if has_v else self.dataset.n
        fits_one_row_per_group = (
            getattr(self.estimator, "weight_scheme", None) == "collapse" and groups is not None
        )
        if fits_one_row_per_group:
            rho = getattr(self.estimator, "rho", DEFAULT_RHO)
            if has_v:
                y, second, X = collapse_groups(y, second, X, groups, rho=rho)
            else:
                y, second, X = collapse_groups_by_n(y, second, X, groups, rho=rho)
            groups = np.arange(y.shape[0])
        return y, second, X, groups, has_v

    @property
    @lru_cache(maxsize=1)
    def fe_se(self):
        """Get fixed-effect standard error."""
        cov = self.fe_cov.copy()
        if cov.ndim == 2:
            cov = cov[None, :, :]

        return np.sqrt(np.diagonal(cov)).T

    @lru_cache(maxsize=16)
    def get_fe_stats(self, alpha=0.05):
        """Get fixed-effect statistics.

        Parameters
        ----------
        alpha : :obj:`float`, optional
            Default = 0.05.

        Returns
        -------
        :obj:`dict`
            A dictionary of fixed-effect statistics.
            The dictionary has the following keys:

            =========== ==========================================================================
            est         The parameter estimate for the regressor.
            se          The standard error of the estimate.
            z           The z score of the estimate.
            p           The two-tailed p value of the estimate.
            logp        The natural logarithm of ``p``.
            ci_l/ci_u   Lower and upper bounds of the estimate.
            =========== ==========================================================================

        Notes
        -----
        ``est / se`` is referred to a t distribution whenever the estimator
        recorded degrees of freedom for it, and to a normal distribution
        otherwise; :attr:`fe_dof` says which correction supplied them. With group
        labels the standard errors are cluster-robust and the reference has
        Satterthwaite degrees of freedom :footcite:p:`tipton2015small`; without
        them, under the default ``small_sample_correction="knapp-hartung"``, the
        covariance carries the
        Knapp-Hartung scale factor :footcite:p:`knapp2003improved` and the
        reference has ``K - P``. ``small_sample_correction="wald"`` gives a normal
        reference, as before.

        Under ``"knapp-hartung"`` a standard error of exactly zero reaches this
        method when the weighted residuals are all zero -- the scale factor
        correctly reporting that a perfectly fitting dataset says nothing about
        how uncertain the coefficients are. The ``undefined`` branch below turns
        that into a NaN p-value rather than a maximally significant one.

        The tail is computed in logs because ``p`` cannot express the
        transform's own input: a two-tailed normal p is exactly zero from
        ``|z| = 38.5`` on, and every deviate past that would come back
        infinite. Via ``logp``, ``z`` grows like ``sqrt(2 |logp|)`` without
        bound.

        .. versionchanged:: 0.0.11
            ``p`` is no longer floored at ``numpy.finfo(float).eps``. The floor
            read a limit of precision as one of magnitude, truncating ``z`` at
            ``norm.isf(eps / 2) = 8.21`` for every estimate below 2.2e-16,
            however far below it fell.

        References
        ----------
        .. footbibliography::

        """
        beta, se = self.fe_params, self.fe_se

        # Cluster-robust standard errors are asymptotic in the number of
        # groups, so refer them to a t distribution rather than a normal.
        dof = self.fe_dof
        # A zero standard error divides to +-inf, or to NaN if the estimate is
        # zero too. Both are answered by the ``undefined`` mask below rather
        # than by a warning, so the arithmetic is allowed to produce them.
        with np.errstate(invalid="ignore", divide="ignore"):
            stat = beta / se
            if dof is None:
                crit = ss.norm.ppf(1 - alpha / 2)
                log_tail = ss.norm.logsf(np.abs(stat))
                z = stat
            else:
                crit = ss.t.ppf(1 - alpha / 2, dof)
                log_tail = ss.t.logsf(np.abs(stat), dof)
                z = -np.sign(stat) * ndtri_exp(log_tail)

            # Two tails, so an added log(2). The cap is against log(1), which
            # the sum can exceed only by rounding at a statistic of essentially
            # zero; it is not a floor on the tail.
            logp = np.minimum(log_tail + math.log(2.0), 0.0)
            p = np.exp(logp)

        # A standard error that is zero or non-finite carries no information,
        # but "est / 0" is +-inf and yields p = 0 -- maximally significant. Mark
        # those entries undefined instead of maximally certain.
        undefined = ~np.isfinite(se) | (se <= 0)

        stats = {
            "est": beta,
            "se": se,
            "ci_l": np.where(undefined, np.nan, beta - crit * se),
            "ci_u": np.where(undefined, np.nan, beta + crit * se),
            "z": np.where(undefined, np.nan, z),
            "p": np.where(undefined, np.nan, p),
            "logp": np.where(undefined, np.nan, logp),
        }

        return stats

    @property
    def fe_dof(self):
        """Get the degrees of freedom used for fixed-effect inference.

        An array of shape ``(p, d)``, one per predictor and parallel dataset, or
        None when a normal reference is used instead. Two different corrections
        can supply them, and they are not interchangeable: with group labels,
        Satterthwaite degrees of freedom for the CR2 cluster-robust standard
        errors :footcite:p:`tipton2015small`; without them, ``K - P``, the
        residual degrees of freedom of the Knapp-Hartung adjustment
        :footcite:p:`knapp2003improved`, or None under
        ``small_sample_correction="wald"``. The
        Which one produced a given array is recorded rather than inferable from
        it: ``estimator.n_groups_`` is None for the model-based path and the group
        count for the cluster-robust one. It is not safe to read the provenance
        off the values -- balanced groups with an intercept-only model give a
        constant Satterthwaite dof, so "constant" does not imply ``K - P``.

        .. versionchanged:: 0.0.11
            No longer None for an estimator fitted without group labels, unless
            ``small_sample_correction="wald"`` was requested.

        The rest of this applies to the cluster-robust case. These are *not* the
        naive :math:`m - p` of
        :footcite:t:`hedges2010robust`. That count is right only when weight is
        spread evenly across groups; when a predictor is unbalanced at the
        group level it badly overstates the information available, and the
        resulting test rejects far too often. See
        :func:`~pymare.stats.satterthwaite_dof`.

        Read these before the p-values. :footcite:t:`tipton2015small` established
        that the approximation holds its nominal level only while the degrees of
        freedom exceed roughly ``pymare.stats.MIN_DOF_FOR_SATTERTHWAITE``; below
        that the reference distribution is outside its validated range and
        :func:`~pymare.stats.satterthwaite_dof` warns. A comfortable number of
        groups does not guarantee comfortable degrees of freedom, because these
        depend on how evenly each *predictor* is spread across groups
        :footcite:p:`pustejovsky2018small,imbens2016robust`.

        References
        ----------
        .. footbibliography::

        """
        dof = getattr(self.estimator, "params_", {}).get("dof")
        if dof is None:
            return None

        dof = np.asarray(dof, dtype=float)
        # _loopable stacks per-dataset results, which can drop a length-1
        # predictor axis; restore the (p, d) orientation the stats expect.
        return dof.reshape(self.fe_params.shape)

    @lru_cache(maxsize=16)
    def get_re_stats(self, method="QP", alpha=0.05):
        """Get random-effect statistics.

        .. warning::

            This method relies on the ``.dataset`` attribute, so the original Estimator must have
            be fitted with ``fit_dataset``, not ``fit``.

        Parameters
        ----------
        method : {"QP"}, optional
            Method for estimating the confidence interval of the tau^2 estimate.
            Default = "QP" :footcite:p:`viechtbauer2007confidence`.
        alpha : :obj:`float`, optional
            Default = 0.05.

        Returns
        -------
        :obj:`dict`
            A dictionary of random-effect statistics.
            The dictionary has the following keys:

            =========== ==========================================================================
            tau^2       The parameter estimate for the regressor.
            ci_l/ci_u   Lower and upper bounds of the tau^2 estimate.
            =========== ==========================================================================

        References
        ----------
        .. footbibliography::
        """
        if self.dataset is None:
            raise ValueError("The Dataset is unavailable. This method requires a Dataset.")

        if method == "QP":
            n_datasets = np.atleast_2d(self.tau2).shape[1]
            if n_datasets > 10:
                warn(
                    "Method 'QP' is not parallelized; it may take a while to "
                    f"compute CIs for {n_datasets} parallel tau^2 values."
                )

            # Make sure we have an estimate of v if it wasn't observed
            analysis_y, v, analysis_X, analysis_groups = self._analysis_arrays()

            cis = []
            for i in range(n_datasets):
                args = {
                    "y": analysis_y[:, i],
                    "v": v[:, i],
                    "X": analysis_X,
                    "alpha": alpha,
                    "groups": analysis_groups,
                }

                try:
                    q_cis = q_profile(**args)
                except Exception:
                    q_cis = {"ci_l": np.nan, "ci_u": np.nan}

                cis.append(q_cis)

        else:
            raise ValueError(
                "Invalid CI method '{}'; currently only 'QP' is available.".format(method)
            )

        return {
            "tau^2": self.tau2,
            "ci_l": np.array([ci["ci_l"] for ci in cis]),
            "ci_u": np.array([ci["ci_u"] for ci in cis]),
        }

    @lru_cache(maxsize=16)
    def get_heterogeneity_stats(self):
        """Get heterogeneity statistics.

        .. warning::

            This method relies on the ``.dataset`` attribute, so the original Estimator must have
            be fitted with ``fit_dataset``, not ``fit``.

        Returns
        -------
        :obj:`dict`
            A dictionary with the associated heterogeneity statistics.
            The keys to this dictionary are:

            ======= ==============================================================================
            Q       Cochran's Q :footcite:p:`cochran1954combination`.
                    This measure follows a chi-squared distribution, with n - k degrees of
                    freedom, where n is the number of independent observations and k is the
                    number of regressors.
            p(Q)    P values associated with the Cochran's Q values.
            logp(Q) Natural logarithms of the ``p(Q)`` values, computed directly and
                    therefore still finite where ``p(Q)`` has underflowed to zero.
            I^2     The proportion of the variance in input estimates that is due to heterogeneity
                    instead of sampling error :footcite:p:`higgins2002quantifying`.
                    This measure is bounded from 0 to 100.
            H       The ratio of the standard deviation of the estimated overall effect size from
                    a random-effects meta-analysis compared to the standard deviation from a
                    fixed-effect meta-analysis :footcite:p:`higgins2002quantifying`.
            ======= ==============================================================================

        References
        ----------
        .. footbibliography::
        """
        if self.dataset is None:
            raise ValueError("The Dataset is unavailable. This method requires a Dataset.")

        y, v, X, groups = self._analysis_arrays()
        q_fe = q_gen(y, v, X, 0, groups)
        # Q counts independent units, which is one per group whichever way the
        # dependence was modelled: by aggregating the rows or by reweighting them.
        n_units = y.shape[0] if groups is None else encode_groups(groups)[1].size
        df = n_units - X.shape[1]
        if df <= 0:
            # Collapsing to one row per group makes df = m - p, which reaches
            # zero far more easily than the old K - p. Q is then identically
            # zero and I^2 / H are 100% / inf from pure rounding noise, which
            # reads as total heterogeneity rather than no information.
            nan = np.full(np.shape(q_fe), np.nan)
            return {
                "Q": nan,
                "p(Q)": nan.copy(),
                "logp(Q)": nan.copy(),
                "I^2": nan.copy(),
                "H": nan.copy(),
            }

        i2 = np.maximum(100.0 * (q_fe - df) / q_fe, 0.0)
        h = np.maximum(np.sqrt(q_fe / df), 1.0)
        logp = log_chi2_sf(q_fe, df)
        return {"Q": q_fe, "p(Q)": np.exp(logp), "logp(Q)": logp, "I^2": i2, "H": h}

    def to_df(self, alpha=0.05):
        """Return a pandas DataFrame summarizing fixed effect results.

        .. warning::

            This method only works for one-dimensional results.

        .. warning::

            This method relies on the ``.dataset`` attribute, so the original Estimator must have
            be fitted with ``fit_dataset``, not ``fit``.

        Parameters
        ----------
        alpha : :obj:`float`, optional
            Default = 0.05.

        Returns
        -------
        df : :obj:`pandas.DataFrame`
            DataFrame summarizing fixed effect results.
            The DataFrame will have one row for each regressor, and the following columns:

            =========== ==========================================================================
            name        Name of the regressor.
            estimate    The parameter estimate for the regressor.
            se          The standard error of the estimate.
            z-score     The z score of the estimate.
            p-value     The p value the estimate.
            -log10(p)   The p value on a base-10 log scale.
            ci_+        Lower and upper bounds of the estimate. There will be two columns, with
                        names based on the ``alpha`` value. For example, if ``alpha = 0.05``,
                        the CI columns will be ``"ci_0.025"`` and ``"ci_0.975"``.
            =========== ==========================================================================
        """
        if self.dataset is None:
            raise ValueError("The Dataset is unavailable. This method requires a Dataset.")

        b_shape = self.fe_params.shape
        if len(b_shape) > 1 and b_shape[1] > 1:
            raise ValueError(
                "More than one set of results found! A summary "
                "table cannot be displayed for multidimensional "
                "results at the moment."
            )

        fe_stats = self.get_fe_stats(alpha).items()
        df = pd.DataFrame({k: v.ravel() for k, v in fe_stats})
        df["name"] = self.dataset.X_names
        df["logp"] = np.abs(df["logp"]) / math.log(10.0)
        df = df.loc[:, ["name", "est", "se", "z", "p", "logp", "ci_l", "ci_u"]]
        ci_l = "ci_{:.6g}".format(alpha / 2)
        ci_u = "ci_{:.6g}".format(1 - alpha / 2)
        df.columns = ["name", "estimate", "se", "z-score", "p-value", "-log10(p)", ci_l, ci_u]
        return df

    def permutation_test(self, n_perm=1000):
        """Run permutation test.

        .. warning::

            This method relies on the ``.dataset`` attribute, so the original Estimator must have
            be fitted with ``fit_dataset``, not ``fit``.

        Parameters
        ----------
        n_perm : :obj:`int`, optional
            Number of permutations to generate. The actual number used may be smaller in the event
            of an exact test (see below), but will never be larger.
            Default = 1000.

        Returns
        -------
        :obj:`~pymare.results.PermutationTestResults`
            An instance of class PermutationTestResults.

        Notes
        -----
        If the number of possible permutations is smaller than n_perm, an exact test will be
        conducted.
        Otherwise an approximate test will be conducted by randomly shuffling the outcomes n_perm
        times (or, for intercept-only models, by randomly flipping their signs).
        Note that for closed-form estimators (e.g., 'DL' and 'HE'), permuted datasets are
        estimated in parallel.
        This means that one can often set very high n_perm values (e.g., 100k) with little
        performance degradation.
        """
        if self.dataset is None:
            raise ValueError("The Dataset is unavailable. This method requires a Dataset.")

        analysis_y, analysis_second, analysis_X, analysis_groups, has_v = (
            self._permutation_arrays()
        )
        n_obs, n_datasets = analysis_y.shape
        analysis_second = broadcast_columns(analysis_second, n_datasets)
        has_mods = analysis_X.shape[1] > 1

        # Rows sharing a group label are dependent, so they are exchangeable
        # only as whole groups: flipping or shuffling them independently builds
        # a null that is far too narrow. Under weight_scheme='collapse' (and now
        # 'rescale') the arrays above are already one row per group, but
        # 'individual' keeps every row while still using cluster-robust errors,
        # so the unit has to be recovered from the labels here.
        if analysis_groups is not None:
            group_codes, group_labels = encode_groups(analysis_groups, n_observations=n_obs)
            n_units = group_labels.size
        else:
            group_codes = None
            n_units = n_obs

        fe_stats = self.get_fe_stats()

        # self.tau2 directly, not get_re_stats()["tau^2"] -- they are the same
        # value, but the latter also profiles the Q statistic for a confidence
        # interval that is never read, which dominates the runtime here when
        # there are many parallel datasets.
        # (D,) whatever the estimator reported: the looping estimators return
        # tau^2 as (1, D), so indexing it per dataset used to take a whole row.
        tau2 = np.asarray(self.tau2, dtype=float).reshape(-1)
        if tau2.size == 1 and n_datasets > 1:
            tau2 = np.repeat(tau2, n_datasets)

        # create results arrays
        fe_p = np.zeros_like(self.fe_params)
        rfx = self.tau2 is not None
        tau_p = np.zeros((n_datasets,)) if rfx else None

        # Calculate # of permutations and determine whether to use exact test
        if has_mods:
            # Only groups of equal size may swap places; see _expand_unit_order.
            unit_classes = _exchangeable_unit_classes(group_codes, n_units)
            n_exact = math.prod(math.factorial(unit.size) for unit in unit_classes)
            if group_codes is not None and n_exact == 1:
                raise ValueError(
                    "No non-trivial permutation of the groups exists: every group "
                    "contributes a different number of rows, and a permuted dataset "
                    "is refit against the original labels, so a group can only take "
                    "the place of an equally sized one. Use weight_scheme='collapse' "
                    "to reduce each group to one row, which makes all groups "
                    "exchangeable."
                )
        else:
            n_exact = 2**n_units
            # The same inclusive condition as `exact` below; on the strict one
            # these were left undefined at exactly n_perm == 2**m.
            if n_exact <= n_perm:
                perms = np.array(list(itertools.product([-1, 1], repeat=n_units))).T

        # <=, not <: at n_perm == 2**m the exhaustive test costs the same as
        # the random one and is not an approximation.
        exact = n_exact <= n_perm
        if exact:
            n_perm = n_exact

        # Loop over parallel datasets
        for i in range(n_datasets):
            y = analysis_y[:, i]
            y_perm = np.repeat(y[:, None], n_perm, axis=1)

            # for v, we might actually be working with n, depending on estimator
            v = analysis_second[:, i]

            v_perm = np.repeat(v[:, None], n_perm, axis=1)

            if has_mods:
                # Shuffle whole groups, and carry y and v together: shuffling
                # them independently would break the (y_i, v_i) pairing and
                # widen the null on top of the dependence problem.
                unit_order = (
                    _iter_unit_orders(unit_classes, n_units)
                    if exact
                    else (_random_unit_order(unit_classes, n_units) for _ in range(n_perm))
                )
                for j, order in enumerate(unit_order):
                    rows = _expand_unit_order(np.asarray(order), group_codes, n_obs)
                    y_perm[:, j] = y[rows]
                    v_perm[:, j] = v[rows]
            else:
                if exact:
                    signs = perms
                else:
                    signs = np.random.choice(np.array([-1, 1]), (n_units, n_perm))
                if group_codes is not None:
                    signs = signs[group_codes]
                y_perm *= signs

            # Pass parameters, remembering that v may actually be n
            kwargs = {"y": y_perm, "X": analysis_X}
            kwargs["v" if has_v else "n"] = v_perm
            if analysis_groups is not None:
                kwargs["g"] = analysis_groups
            # A copy: fit() overwrites params_, including the "dof" entry that
            # fe_dof reads, so permuting through the live estimator would leave
            # the results object reporting permutation-shaped degrees of
            # freedom (or raising on reshape).
            params = copy.copy(self.estimator).fit(**kwargs).params_

            fe_obs = fe_stats["est"][:, i]
            if fe_obs.ndim == 1:
                fe_obs = fe_obs[:, None]
            # <=, not <: a permuted statistic that ties with the observed one
            # is at least as extreme, and excluding ties makes the test
            # anti-conservative on discrete or degenerate data.
            fe_p[:, i] = (np.abs(fe_obs) <= np.abs(params["fe_params"])).mean(1)
            if rfx:
                abs_obs = np.abs(tau2[i])
                tau_p[i] = (abs_obs <= np.abs(params["tau2"])).mean()

        # p-values can't be smaller than 1/n_perm
        params = {"fe_p": np.maximum(1 / n_perm, fe_p)}
        if rfx:
            params["tau2_p"] = np.maximum(1 / n_perm, tau_p)

        return PermutationTestResults(self, params, n_perm, exact)


class CombinationTestResults:
    """Container for results generated by p-value combination methods.

    Parameters
    ----------
    estimator : :obj:`~pymare.estimators.estimators.BaseEstimator`
        The estimator used to produce the results.
    dataset : :obj:`~pymare.core.Dataset`
        A Dataset instance containing the inputs to the estimator.
    z : :obj:`numpy.ndarray`, optional
        Array of z-scores. Default = None.
    p : :obj:`numpy.ndarray`, optional
        Array of right-tailed p-values. Default = None.
    logp : :obj:`numpy.ndarray`, optional
        Array of natural logarithms of the right-tailed p-values. Default = None.
    """

    def __init__(self, estimator, dataset, z=None, p=None, logp=None):
        self.estimator = estimator
        self.dataset = dataset
        if p is None and z is None and logp is None:
            raise ValueError("One of 'z', 'p' or 'logp' must be provided.")
        self._z = z
        self._p = p
        self._logp = logp

    @property
    @lru_cache(maxsize=1)
    def logp(self):
        """Natural logarithms of the p-values."""
        if self._logp is None:
            with np.errstate(divide="ignore"):
                self._logp = log_ndtr(-self._z) if self._z is not None else np.log(self._p)
        return self._logp

    @property
    @lru_cache(maxsize=1)
    def z(self):
        """Z-values."""
        if self._z is None:
            self._z = -ndtri_exp(self.logp)
        return self._z

    @property
    @lru_cache(maxsize=1)
    def p(self):
        """P-values."""
        if self._p is None:
            self._p = np.exp(self.logp)
        return self._p

    def permutation_test(self, n_perm=1000):
        """Run permutation test.

        .. warning::

            This method relies on the ``.dataset`` attribute, so the original Estimator must have
            be fitted with ``fit_dataset``, not ``fit``.

        Parameters
        ----------
        n_perm : :obj:`int`, optional
            Number of permutations to generate. The actual number used may be smaller in the event
            of an exact test (see below), but will never be larger.
            Default = 1000.

        Returns
        -------
        :obj:`~pymare.results.PermutationTestResults`
            An instance of class PermutationTestResults.

        Notes
        -----
        If the number of possible permutations is smaller than n_perm, an
        exact test will be conducted. Otherwise an approximate test will be
        conducted by randomly shuffling the outcomes n_perm times (or, for
        intercept-only models, by randomly flipping their signs). Permuted
        datasets are processed in parallel. This means that one can often
        set very high n_perm values (e.g., 100k) with little performance
        degradation.
        """
        if self.dataset is None:
            raise ValueError("The Dataset is unavailable. This method requires a Dataset.")

        # 'undirected' takes abs(z) before combining, so its statistic is a
        # function of |z| alone and every sign-flip permutation reproduces the
        # observed value exactly. The null distribution is a single point and
        # the resulting p-value is always 1 / n_perm, which looks like a
        # significant result rather than a failure. There is no sign-flip null
        # for a statistic that discards sign, so refuse instead of inventing one.
        if getattr(self.estimator, "mode", None) == "undirected":
            raise ValueError(
                "Permutation testing is not available for mode='undirected'. "
                "The combined statistic depends only on |z|, so flipping signs "
                "leaves it unchanged and the permutation null is degenerate. "
                "Use mode='directed' or mode='concordant'."
            )

        n_obs, n_datasets = self.dataset.y.shape
        groups = getattr(self.dataset, "g", None)
        # Dependence-labelled rows are exchangeable only as complete groups.
        if groups is not None:
            groups = np.asarray(groups).ravel()
            # encode_groups, not np.unique: labels only have to be hashable.
            group_codes, group_labels = encode_groups(groups, n_observations=n_obs)
            n_units = group_labels.size
        else:
            group_codes = None
            n_units = n_obs

        # create results arrays
        p_p = np.zeros_like(self.z)

        # Calculate # of permutations and determine whether to use exact test
        n_exact = 2**n_units
        if n_exact <= n_perm:
            perms = np.array(list(itertools.product([-1, 1], repeat=n_units))).T
            exact = True
            n_perm = n_exact
        else:
            exact = False

        # Initialize a copy of the estimator to prevent overwriting results
        est = copy.copy(self.estimator)

        # Estimate the dependence once, from the observed data, and hold it
        # fixed across permutations. Leaving it None makes each refit
        # re-estimate it from y_perm, whose second axis is permutations rather
        # than features -- and because whole groups share a sign, rows within a
        # group come back near-perfectly correlated along that axis. That
        # inflates the variance correction, and with n_perm < 2 it cannot be
        # estimated at all.
        permutation_corr = getattr(self.estimator, "corr_", None)
        if permutation_corr is None and groups is not None and n_datasets > 1:
            # Skip the centering when every row is identical, exactly as both
            # estimators do. Centering those rows leaves zeros, whose correlation
            # is undefined and would be frozen as the identity -- while the fit
            # being tested read the same rows as perfectly correlated.
            y_obs = self.dataset.y
            all_rows_same = np.all(np.equal(y_obs, y_obs[0]), axis=0).all()
            observed = y_obs if all_rows_same else y_obs - y_obs.mean(0)
            with np.errstate(invalid="ignore", divide="ignore"):
                permutation_corr = np.corrcoef(observed, rowvar=True)
            permutation_corr = np.where(np.isfinite(permutation_corr), permutation_corr, 0.0)
            np.fill_diagonal(permutation_corr, 1.0)

        # Loop over parallel datasets
        for i in range(n_datasets):
            y = self.dataset.y[:, i]
            y_perm = np.repeat(y[:, None], n_perm, axis=1)

            if exact:
                signs = perms
            else:
                signs = np.random.choice(np.array([-1, 1]), (n_units, n_perm))
            if group_codes is not None:
                signs = signs[group_codes]
            y_perm *= signs

            # Some combination tests can handle weights, which the Dataset
            # carries as ``n``. They are per-observation, so this dataset's
            # column has to be repeated across permutations to line up with
            # ``y_perm``; passing the (K, D) array straight through would only
            # happen to broadcast when D equals n_perm.
            kwargs = {"z": y_perm}
            weights = self.dataset.n
            if "w" in getfullargspec(est.fit).args and weights is not None:
                # A single column, not one per permutation. Stouffer broadcasts
                # either form, but Fisher requires one scalar weight per
                # observation and rejects the tiled version outright.
                column = i if weights.shape[1] > 1 else 0
                kwargs["w"] = weights[:, column, None]
            if groups is not None:
                kwargs["g"] = groups
                kwargs["corr"] = permutation_corr
            params = est.fit(**kwargs).params_

            observed = np.ravel(self.logp)[i]
            null = np.ravel(params["logp"])
            p_p[i] = (null <= observed).mean()

        # p-values can't be smaller than 1/n_perm
        p_p = np.maximum(1 / n_perm, p_p)

        return PermutationTestResults(self, {"fe_p": p_p}, n_perm, exact)


class PermutationTestResults:
    """Lightweight container to hold and display permutation test results."""

    def __init__(self, results, perm_p, n_perm, exact=False):
        self.results = results
        self.perm_p = perm_p
        self.n_perm = n_perm
        self.exact = exact

    def to_df(self, **kwargs):
        """Export permutation test results as a pandas DF.

        Parameters
        ----------
        **kwargs
            Keyword arguments to pass onto to_df() calls of parent
            results class (e.g., in case of MetaRegressionResults class,
            `alpha` is available).

        Returns
        -------
        :obj:`pandas.DataFrame`
            A pandas DataFrame that adds columns to the standard fixed effect
            result table based on permutation test results. A column is added
            for every name found in both the parent DF and the params
            dictionary passed at initialization.
        """
        df = self.results.to_df(**kwargs)
        c_ind = list(df.columns).index("p-value")
        df.insert(c_ind + 1, "p-value (perm.)", self.perm_p["fe_p"])
        return df


def _arviz_credible_interval_kwargs(ci):
    """Return the ArviZ ``summary()`` arguments that request a `ci`% HDI.

    Parameters
    ----------
    ci : :obj:`float`
        Desired width of the credible interval, as a percentage.

    Returns
    -------
    :obj:`dict`
        Keyword arguments for the installed ArviZ version's ``summary()``.

    Notes
    -----
    ArviZ 1.0 renamed ``hdi_prob`` to ``ci_prob`` and paired it with a
    ``ci_kind`` defaulting to an equal-tailed rather than a highest-density
    interval, so ``ci_kind="hdi"`` is needed to keep ``ci`` meaning the same
    thing across both versions.

    ``round_to="none"`` is not cosmetic: ArviZ 1.x otherwise formats the summary
    for display by converting the floats to strings, so arithmetic on the
    returned DataFrame would silently concatenate. ArviZ 0.x has no such
    argument.
    """
    if int(az.__version__.split(".")[0]) >= 1:
        return {"ci_prob": ci / 100.0, "ci_kind": "hdi", "round_to": "none"}
    return {"hdi_prob": ci / 100.0}


def _accepts_var_names(plotter):
    """Report whether an ArviZ plotting function takes a ``var_names`` argument.

    Parameters
    ----------
    plotter : callable
        A function from the ArviZ namespace.

    Returns
    -------
    :obj:`bool`
        True when ``var_names`` can be passed to it.
    """
    try:
        return "var_names" in signature(plotter).parameters
    except (TypeError, ValueError):
        return False


class BayesianMetaRegressionResults:
    """Container for MCMC sampling-based PyMARE meta-regression estimators.

    Parameters
    ----------
    data : :obj:`cmdstanpy.CmdStanMCMC` or :obj:`arviz.InferenceData`
        Either a CmdStanMCMC instance returned from CmdStanPy or an object ArviZ
        already understands (an InferenceData under ArviZ 0.x, a DataTree under 1.x).
    dataset : :obj:`~pymare.core.Dataset`
        A Dataset instance containing the inputs to the estimator.
    ci : :obj:`float`, optional
        Desired width of the credible interval, as a percentage, used as the
        default for :meth:`summary`. Default = 95.0 (95%).

    Notes
    -----
    .. versionchanged:: 0.0.5

        - Accepts a :obj:`cmdstanpy.CmdStanMCMC` rather than a PyStan fit.
        - ``ci`` now sets the width of the interval :meth:`summary` reports. It
          was previously stored and never used, so the interval was whatever
          ArviZ defaulted to.
    """

    def __init__(self, data, dataset, ci=95.0):
        if az is None:
            raise ValueError(
                "ArviZ package must be installed in order to work "
                "with the BayesianMetaRegressionResults class."
            )
        if not 0 < ci < 100:
            raise ValueError(f"Invalid ci {ci!r}; must lie in (0, 100).")

        # Convert here, not on use: ArviZ 1.x removed the automatic dispatch that
        # let summary() accept a sampler fit, so a raw fit would fail at every
        # call site instead of this one. The import is lazy because a caller
        # passing an already-converted object should not need cmdstanpy.
        try:
            from cmdstanpy import CmdStanMCMC
        except ImportError:
            CmdStanMCMC = ()
        if isinstance(data, CmdStanMCMC):
            data = az.from_cmdstanpy(data)

        self.data = data
        self.dataset = dataset
        self.ci = ci

    def summary(self, include_theta=False, **kwargs):
        """Summarize the posterior estimates via ArviZ.

        Parameters
        ----------
        include_theta : :obj:`bool`, optional
            Whether or not to include the estimated group-level means in the summary.
            Default = False.
        **kwargs
            Optional keyword arguments to pass onto ArviZ's summary(). Anything
            passed here wins over the defaults derived from ``ci``.

        Returns
        -------
        :obj:`pandas.DataFrame`
            A pandas DataFrame, unless the `fmt="xarray"` argument is passed in
            kwargs, in which case an xarray Dataset is returned.

        Notes
        -----
        The columns follow whichever ArviZ version is installed; 1.x renamed
        several of them. Index by label rather than by position.
        """
        var_names = ["beta", "tau2"]
        if include_theta:
            var_names.append("theta")
        var_names = kwargs.pop("var_names", var_names)
        for key, value in _arviz_credible_interval_kwargs(self.ci).items():
            kwargs.setdefault(key, value)
        return az.summary(self.data, var_names, **kwargs)

    def plot(self, kind="trace", include_theta=False, **kwargs):
        """Generate various plots of the posterior estimates via ArviZ.

        Parameters
        ----------
        kind : :obj:`str`, optional
            The type of ArviZ plot to generate. Can be any named function of the form "plot_{}" in
            the ArviZ namespace (e.g., 'trace', 'forest', 'posterior', etc.).
            Default = 'trace'.
        include_theta : :obj:`bool`, optional
            Whether or not to include the estimated group-level means in the plot.
            Default = False.
        **kwargs
            Optional keyword arguments passed onto the corresponding
            ArviZ plotting function (see ArviZ docs for details). Passing
            ``var_names`` overrides the selection ``include_theta`` implies.

        Returns
        -------
        A matplotlib or bokeh object, depending on plot kind and kwargs.

        Raises
        ------
        ValueError
            If ArviZ has no plotting function of the requested kind.

        Notes
        -----
        The plotted variables default to the ones :meth:`summary` reports rather
        than everything recorded. A fitted model has one ``theta`` per group, so
        plotting everything gives one panel per group -- illegible, and a hard
        error under ArviZ 1.x, which caps panels at
        ``rcParams["plot.max_subplots"]``.
        """
        name = "plot_{}".format(kind)
        # Three-argument getattr: the two-argument form raises AttributeError
        # before the check below can turn it into the documented ValueError.
        plotter = getattr(az, name, None)
        if plotter is None:
            raise ValueError("ArviZ has no plotting function '{}'.".format(name))

        # Not every ArviZ plot takes var_names -- plot_energy, for one, takes
        # only the data -- so only offer the default to those that do.
        if "var_names" not in kwargs and _accepts_var_names(plotter):
            kwargs["var_names"] = ["beta", "tau2", "theta"] if include_theta else ["beta", "tau2"]

        return plotter(self.data, **kwargs)
